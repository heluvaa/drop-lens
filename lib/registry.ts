/** Index cepat: alamat lowercase → entri registry. */
export const BY_TOKEN = new Map<string, RegistryEntry>();
/** Index cepat: `${chain}|${symbol}` uppercase → entri registry (fallback nama). */
export const BY_SYMBOL = new Map<string, RegistryEntry>();

for (const e of REGISTRY) {
  if (e.kind === "evm") BY_TOKEN.set(e.token.toLowerCase(), e);
  else BY_TOKEN.set(e.token, e);
  BY_SYMBOL.set(`${e.chain}|${e.symbol.toUpperCase()}`, e);
}

/** Airdrop yang ketemu persis di chain ini (untuk panduan UI). */
export function registryForChain(chainKey: string): RegistryEntry[] {
  return REGISTRY.filter((e) => e.chain === chainKey);
}
